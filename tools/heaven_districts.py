def main():
    os.makedirs(OUT, exist_ok=True)
    lay = json.load(open(LAYOUT))
    for isl in lay["islands"]:
        d = D(isl["id"])
        rng = random.Random(isl["id"])
        f = BUILD[isl["kind"]]
        if f in (mall, hub): f(d)
        else: f(d, rng)
        lim = isl["radius"] * 0.8
        for p in d.pieces:   # keep everything on the plaza
            x, z = p["at"]
            if math.hypot(x, z) > lim - 4 and p["type"] not in ("coaster", "canal_ring", "sand"):
                s = (lim - 4) / math.hypot(x, z); p["at"] = [round(x * s, 2), round(z * s, 2)]
        d.dump({"paving": {"color": {"beach": SAND, "gardens": "#a9c99a", "spirit": "#f4f1ff", "beyond": "#e8e4ff", "warehouses": "#bdb8b0"}.get(isl["kind"], MARBLE)}})
    print("wrote", len(lay["islands"]), "district files")

if __name__ == "__main__":
    main()
