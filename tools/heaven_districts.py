#!/usr/bin/env python3
"""HEAVEN-1: compose the default Heaven district files (data/heaven/districts/<island>.json).

The files are plain data that the game renders (scripts/heaven/heaven_builder.gd) and that companions
edit at runtime (scripts/heaven/heaven_edits.gd overlays user edits on top). Run this only to reset the
DEFAULT layout; runtime edits never touch these files.

Local frame per island: origin = island centre at plaza height, -z faces the Main Mall (the floating
road arrives there), +-x face the ring bridges. A clear cross 14 m wide is kept for the roads/bridges.
Units: metres, yaw in degrees. Real-world sizes: doors 3.2 x 3.6 m, storeys 4 m.
"""
import json, math, os, random

OUT = os.path.join(os.path.dirname(__file__), "..", "data", "heaven", "districts")
LAYOUT = os.path.join(os.path.dirname(__file__), "..", "data", "heaven", "heaven_layout.json")

MARBLE = "#ede8de"; PEARL = "#f7f5fb"; GOLD = "#f0c35a"; SKY = "#8fd0ff"; ROSE = "#ff7ac0"
STONE = "#c9c3b8"; SAND = "#eed9a6"; WOOD = "#8a6142"; SLATE = "#55606e"; GLASS = "#cfe6ff"

class D:
    def __init__(s, iid): s.id = iid; s.pieces = []; s.n = 0
    def add(s, t, x, z, **kw):
        s.n += 1
        p = {"id": "%s_%s_%d" % (s.id, t, s.n), "type": t, "at": [round(x, 2), round(z, 2)]}
        p.update(kw)
        s.pieces.append(p)
        return p
    def dump(s, extra):
        d = {"_note": "Heaven district pieces (HEAVEN-1). Generated by tools/heaven_districts.py; runtime edits overlay this (user://heaven/edits.json).",
             "schema_version": 1, "island": s.id, "pieces": s.pieces}
        d.update(extra)
        with open(os.path.join(OUT, s.id + ".json"), "w", newline="\n") as f:
            json.dump(d, f, indent=1); f.write("\n")

def lamps(d, r, n, start=0.0):
    for k in range(n):
        a = start + 2 * math.pi * k / n
        x, z = r * math.sin(a), r * math.cos(a)
        if abs(x) < 8 or abs(z) < 8: continue
        d.add("lamp", x, z)

def trees_ring(d, r, n, kind="tree", jitter=0.0, rng=None):
    for k in range(n):
        a = 2 * math.pi * (k + 0.5) / n
        x, z = r * math.sin(a), r * math.cos(a)
        if abs(x) < 9 or abs(z) < 9: continue
        if rng: x += rng.uniform(-jitter, jitter); z += rng.uniform(-jitter, jitter)
        d.add(kind, x, z, h=round(rng.uniform(6, 10), 1) if rng else 8)

def shop_row(d, shops, r, a0, a1, w=16, dep=14, h=8):
    """Shops facing the centre on an arc from angle a0 to a1 (radians, 0 = +z)."""
    n = len(shops)
    for k, sid in enumerate(shops):
        a = a0 + (a1 - a0) * (k + 0.5) / n
        x, z = r * math.sin(a), r * math.cos(a)
        yaw = math.degrees(math.atan2(x, z))   # front (-z local of building) faces the centre
        d.add("shop", x, z, yaw=round(yaw, 1), w=w, d=dep, h=h, shop=sid, color=PEARL, trim=GOLD)

def mall(d):
    d.add("canal_ring", 0, 0, r=96, width=6)
    d.add("dome", 0, 0, r=75, h=48, color=GLASS, trim=GOLD, doors=4)
    # inner ring of shops (8), facing the atrium; gaps at the 4 entrance axes
    ids = ["seraph_threads", "cloudstep_shoes", "halo_hair", "radiance_looks", "gilded_wings", "mall_market_hall", "mall_info", "mall_looks_lab"]
    for q in range(4):
        a0 = math.radians(90 * q + 14); a1 = math.radians(90 * q + 76)
        shop_row(d, ids[q * 2:q * 2 + 2], 56, a0, a1, w=20, dep=14, h=9)
    d.add("fountain", 0, 0, r=9, h=6)
    d.add("column_ring", 0, 0, r=22, n=12, h=12)
    for x, z in [(30, 30), (-30, 30), (30, -30), (-30, -30)]:
        d.add("tree", x, z, h=7)
    lamps(d, 120, 16)
    lamps(d, 150, 20, 0.1)
    for a in range(0, 360, 30):
        r = 135; x, z = r * math.sin(math.radians(a + 15)), r * math.cos(math.radians(a + 15))
        if abs(x) > 10 and abs(z) > 10: d.add("bench", x, z, yaw=a + 15)
    d.add("sign", 0, -100, text="Main Mall", h=8)
    d.add("arch", 0, -103, w=16, h=11)
    d.add("arch", 0, 103, w=16, h=11, yaw=180)
